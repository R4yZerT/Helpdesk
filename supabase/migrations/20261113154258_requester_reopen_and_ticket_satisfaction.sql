-- El cierre del técnico puede devolverse una sola vez al flujo de trabajo
-- usando el estado existente "devuelto"; la reapertura solo la puede pedir
-- el solicitante autenticado dueño del ticket.
create or replace function public.ticket_fsm_check()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  permitido boolean := false;
  sol text;
  es_cancelacion boolean := false;
begin
  if new.estado is not distinct from old.estado then
    return new;
  end if;

  case old.estado::text
    when 'abierto' then permitido := new.estado::text in ('en_proceso', 'programado', 'cerrado');
    when 'en_proceso' then permitido := new.estado::text in ('programado', 'solucionado', 'devuelto', 'cerrado');
    when 'programado' then permitido := new.estado::text in ('en_proceso', 'solucionado', 'cerrado');
    when 'solucionado' then permitido := new.estado::text in ('cerrado', 'devuelto');
    when 'devuelto' then permitido := new.estado::text in ('en_proceso', 'programado', 'cerrado');
    when 'cerrado' then permitido := new.estado::text = 'devuelto';
    else permitido := false;
  end case;

  if not permitido then
    raise exception 'Transición no permitida: % → %', old.estado, new.estado using errcode = '23514';
  end if;

  if old.estado::text = 'cerrado' and new.estado::text = 'devuelto' then
    if auth.uid() is null or auth.uid() <> old.usuario_id then
      raise exception 'Solo el solicitante puede reabrir su ticket cerrado' using errcode = '42501';
    end if;
    new.fecha_resolucion := null;
    return new;
  end if;

  es_cancelacion := old.estado::text = 'abierto'
    and new.estado::text = 'cerrado'
    and old.tecnico_asignado_id is null
    and new.tecnico_asignado_id is null;

  if new.estado::text in ('solucionado', 'cerrado') and not es_cancelacion then
    sol := coalesce(nullif(btrim(new.solucion_aplicada, ' ' || chr(9) || chr(10) || chr(13)), ''), '');
    if char_length(sol) < 5 then
      raise exception 'Solución aplicada requerida (mín. 5 caracteres)' using errcode = '23514';
    end if;
    if char_length(sol) > 5000 then
      raise exception 'Solución máximo 5000 caracteres' using errcode = '23514';
    end if;
    new.solucion_aplicada := sol;
  end if;
  return new;
end;
$$;

drop policy if exists tickets_update_solicitante_reopen on public.tickets;
create policy tickets_update_solicitante_reopen on public.tickets
  for update to authenticated
  using (usuario_id = (select auth.uid()) and estado = 'cerrado')
  with check (usuario_id = (select auth.uid()) and estado = 'devuelto');

create table if not exists public.ticket_satisfaccion (
  id bigint generated by default as identity primary key,
  ticket_id uuid not null unique references public.tickets(id) on delete cascade,
  usuario_id uuid not null references public.profiles(id) on delete cascade,
  calidad_servicio smallint not null check (calidad_servicio between 1 and 5),
  tiempo_respuesta smallint not null check (tiempo_respuesta between 1 and 5),
  comunicacion smallint not null check (comunicacion between 1 and 5),
  solucion_resolvio smallint not null check (solucion_resolvio between 1 and 5),
  comentario text check (comentario is null or char_length(comentario) <= 1000),
  creado_en timestamptz not null default now(),
  constraint ticket_satisfaccion_usuario_ticket_unique unique (ticket_id, usuario_id)
);

alter table public.ticket_satisfaccion enable row level security;
grant select, insert on public.ticket_satisfaccion to authenticated;
grant usage, select on sequence public.ticket_satisfaccion_id_seq to authenticated;

create policy ticket_satisfaccion_select_owner on public.ticket_satisfaccion
  for select to authenticated
  using (usuario_id = (select auth.uid()));

create policy ticket_satisfaccion_insert_closed_owner on public.ticket_satisfaccion
  for insert to authenticated
  with check (
    usuario_id = (select auth.uid())
    and exists (
      select 1 from public.tickets t
      where t.id = ticket_id
        and t.usuario_id = (select auth.uid())
        and t.estado = 'cerrado'
    )
  );

create or replace function public.validar_ticket_satisfaccion()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if not exists (
    select 1
    from public.tickets t
    where t.id = new.ticket_id
      and t.usuario_id = new.usuario_id
      and t.estado = 'cerrado'
  ) then
    raise exception 'La encuesta solo puede enviarse por el solicitante de un ticket cerrado'
      using errcode = '42501';
  end if;
  return new;
end;
$$;

create trigger ticket_satisfaccion_validar
before insert on public.ticket_satisfaccion
for each row execute function public.validar_ticket_satisfaccion();
